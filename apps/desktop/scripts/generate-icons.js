// Render the vector master with the Electron version already used by the app.
// Run from apps/desktop: pnpm exec electron scripts/generate-icons.js
const { app, BrowserWindow, nativeImage } = require("electron");
const { execFileSync } = require("node:child_process");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");

const assets = path.resolve(__dirname, "../assets");

app.whenReady().then(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "linerfy-icons-"));
  let window;
  let exitCode = 0;
  try {
    window = new BrowserWindow({
      width: 1024,
      height: 1024,
      useContentSize: true,
      show: false,
      transparent: true,
      frame: false,
      webPreferences: {
        contextIsolation: true,
        sandbox: true,
        nodeIntegration: false,
      },
    });
    const svg = await fs.readFile(path.join(assets, "app-icon.svg"), "utf8");
    const document =
      '<html style="background:transparent"><body style="margin:0">' +
      svg +
      "</body></html>";
    await window.loadURL(
      "data:text/html;charset=utf-8," + encodeURIComponent(document),
    );
    const image = await window.webContents.capturePage();
    const master = image.resize({ width: 1024, height: 1024, quality: "best" });
    await fs.writeFile(path.join(assets, "app-icon.png"), master.toPNG());
    await renderTray(window);

    if (process.platform === "darwin") {
      const iconset = path.join(temporary, "app-icon.iconset");
      await fs.mkdir(iconset);
      for (const size of [16, 32, 128, 256, 512]) {
        for (const scale of [1, 2]) {
          const pixels = size * scale;
          const suffix = scale === 2 ? "@2x" : "";
          await fs.writeFile(
            path.join(iconset, `icon_${size}x${size}${suffix}.png`),
            master
              .resize({ width: pixels, height: pixels, quality: "best" })
              .toPNG(),
          );
        }
      }
      execFileSync("iconutil", [
        "-c",
        "icns",
        iconset,
        "-o",
        path.join(assets, "app-icon.icns"),
      ]);
    }
    console.log(
      "Rendered app-icon.png, tray-icon.ts" +
        (process.platform === "darwin" ? " and app-icon.icns" : ""),
    );
  } catch (error) {
    console.error(error);
    exitCode = 1;
  } finally {
    window?.destroy();
    await fs.rm(temporary, { recursive: true, force: true });
  }
  app.exit(exitCode);
});

// Menu-bar template icon: black on transparent, 18pt at 1x and 2x. White fills
// in the SVG only mask lines behind them, so they are turned transparent here.
async function renderTray(window) {
  const svg = await fs.readFile(path.join(assets, "tray-icon.svg"), "utf8");
  const urls = {};
  for (const scale of [1, 2]) {
    const pixels = 18 * scale;
    const sized = svg.replace(
      /width="18" height="18"/,
      `width="${pixels}" height="${pixels}"`,
    );
    await window.loadURL(
      "data:text/html;charset=utf-8," +
        encodeURIComponent(
          '<html style="background:transparent"><body style="margin:0">' +
            sized +
            "</body></html>",
        ),
    );
    await new Promise((resolve) => setTimeout(resolve, 300));
    // Capture a rect of the large window: tiny hidden windows fail to capture.
    const image = (
      await window.webContents.capturePage({
        x: 0,
        y: 0,
        width: pixels,
        height: pixels,
      })
    ).resize({ width: pixels, height: pixels, quality: "best" });
    const bitmap = image.toBitmap(); // BGRA
    for (let i = 0; i < bitmap.length; i += 4) {
      const lightness = (bitmap[i] + bitmap[i + 1] + bitmap[i + 2]) / 3;
      const alpha = Math.round(bitmap[i + 3] * (1 - lightness / 255));
      bitmap[i] = 0;
      bitmap[i + 1] = 0;
      bitmap[i + 2] = 0;
      bitmap[i + 3] = alpha;
    }
    const png = nativeImage
      .createFromBitmap(bitmap, { width: pixels, height: pixels })
      .toPNG();
    urls[scale] = "data:image/png;base64," + png.toString("base64");
  }
  await fs.writeFile(
    path.resolve(__dirname, "../src/tray-icon.ts"),
    "// Generated by scripts/generate-icons.js from assets/tray-icon.svg.\n" +
      "/** Monochrome menu-bar template icon, inlined so the tray needs no asset bundling. */\n" +
      `export const TRAY_ICON_DATA_URL =\n  "${urls[1]}";\n` +
      `export const TRAY_ICON_2X_DATA_URL =\n  "${urls[2]}";\n`,
  );
}
